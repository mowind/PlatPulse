//! The two Storage Backends expose one logical schema (ADR 0013, #255).
//!
//! Every Server schema change ships a SQLite migration and a PostgreSQL
//! migration with the same version, and both are required to stay logically
//! equivalent: the same tables, with the same columns in the same order, the
//! same primary keys, indexes, foreign keys, CHECK constraints and triggers.
//! Nothing enforces that at runtime, so this check compares the two live
//! catalogues of a freshly migrated database and fails on the first divergence.
//!
//! The comparison is about meaning, not spelling: a SQLite `TEXT` column and a
//! PostgreSQL `text COLLATE "C"` column are the same column, an `INTEGER PRIMARY KEY`
//! (a rowid alias) and a `BIGINT GENERATED BY DEFAULT AS IDENTITY` are the same
//! key, and `REAL` and `DOUBLE PRECISION` hold the same values.
//!
//! What it compares is structure: table and column names in declaration order,
//! column type class, nullability, whether a default exists, primary keys,
//! index and foreign-key signatures, and the number of CHECK constraints per
//! table. It does not compare the text of a CHECK expression or the value of a
//! default, because the two catalogues spell them differently and a normalizer
//! that hid that would also hide a real change; a migration that weakens a
//! CHECK is therefore reviewed by hand.
//!
//! Without a PostgreSQL test server there is nothing to compare against, so the
//! check reports itself as skipped (`PLATPULSE_TEST_POSTGRES_URL` is unset). The
//! PostgreSQL CI jobs set it, and there the check runs.

use std::collections::{BTreeMap, BTreeSet};

use sqlx::AnyPool;
use sqlx::Row;
use tempfile::TempDir;

use platpulse_server::test_support::{TEST_POSTGRES_URL_ENV, optional_postgres_database};
use platpulse_server::{ServerDatabaseConfig, initialize};

/// One table as both catalogues can describe it.
#[derive(Debug, Default, PartialEq, Eq)]
struct TableSchema {
    /// In declaration order: moving a column is a schema change.
    columns: Vec<Column>,
    primary_key: Vec<String>,
    indexes: BTreeSet<String>,
    foreign_keys: BTreeSet<String>,
    checks: usize,
    triggers: BTreeSet<String>,
}

#[derive(Debug, PartialEq, Eq)]
struct Column {
    name: String,
    /// `text`, `integer`, `real` or `blob`: the SQLite logical type both
    /// backends agree on.
    type_class: &'static str,
    not_null: bool,
    has_default: bool,
}

#[tokio::test]
async fn both_backends_expose_the_same_logical_schema() {
    let Some(postgres) = optional_postgres_database().await else {
        eprintln!(
            "skipping the schema equivalence check: {TEST_POSTGRES_URL_ENV} is unset, so there \
             is no PostgreSQL schema to compare against. The PostgreSQL CI jobs set it."
        );
        return;
    };
    let dir = TempDir::new().expect("create the SQLite test directory");
    let sqlite = initialize(ServerDatabaseConfig::new(dir.path().join("server.db")))
        .await
        .expect("open the SQLite test database");
    assert_eq!(sqlite.storage_backend(), "sqlite");
    assert_eq!(postgres.storage_backend(), "postgres");

    let sqlite_schema = sqlite_schema(sqlite.pool()).await;
    let postgres_schema = postgres_schema(postgres.pool()).await;
    sqlite.close().await;
    postgres.close().await;

    assert!(
        sqlite_schema.len() > 50,
        "the SQLite catalogue reports only {} tables, so the schema did not load",
        sqlite_schema.len()
    );
    let differences = differences(&sqlite_schema, &postgres_schema);
    assert!(
        differences.is_empty(),
        "the Storage Backends diverge; the PostgreSQL baseline must stay logically equivalent \
         to migrations/:\n{}",
        differences.join("\n")
    );
}

/// Every way the two catalogues disagree, one line each.
fn differences(
    sqlite: &BTreeMap<String, TableSchema>,
    postgres: &BTreeMap<String, TableSchema>,
) -> Vec<String> {
    let mut out = Vec::new();
    for name in sqlite.keys() {
        if !postgres.contains_key(name) {
            out.push(format!("table {name}: exists on SQLite only"));
        }
    }
    for name in postgres.keys() {
        if !sqlite.contains_key(name) {
            out.push(format!("table {name}: exists on PostgreSQL only"));
        }
    }
    for (name, left) in sqlite {
        let Some(right) = postgres.get(name) else {
            continue;
        };
        if left.columns != right.columns {
            out.push(format!(
                "table {name}: columns differ\n  sqlite:   {:?}\n  postgres: {:?}",
                left.columns, right.columns
            ));
        }
        if left.primary_key != right.primary_key {
            out.push(format!(
                "table {name}: primary key differs ({:?} on SQLite, {:?} on PostgreSQL)",
                left.primary_key, right.primary_key
            ));
        }
        report_set(name, "index", &left.indexes, &right.indexes, &mut out);
        report_set(
            name,
            "foreign key",
            &left.foreign_keys,
            &right.foreign_keys,
            &mut out,
        );
        report_set(name, "trigger", &left.triggers, &right.triggers, &mut out);
        if left.checks != right.checks {
            out.push(format!(
                "table {name}: {} CHECK constraints on SQLite, {} on PostgreSQL",
                left.checks, right.checks
            ));
        }
    }
    out
}

fn report_set(
    table: &str,
    field: &str,
    sqlite: &BTreeSet<String>,
    postgres: &BTreeSet<String>,
    out: &mut Vec<String>,
) {
    for value in sqlite.difference(postgres) {
        out.push(format!(
            "table {table}: {field} {value} exists on SQLite only"
        ));
    }
    for value in postgres.difference(sqlite) {
        out.push(format!(
            "table {table}: {field} {value} exists on PostgreSQL only"
        ));
    }
}

/// The catalogues also hold bookkeeping that is not part of the domain schema:
/// SQLite's internal tables and the migration history each backend keeps in its
/// own shape.
fn is_internal(name: &str) -> bool {
    name.starts_with("sqlite_") || name == "_sqlx_migrations"
}

/// A quoted SQLite identifier for the pragma table-valued functions.
fn quoted(name: &str) -> String {
    format!("'{}'", name.replace('\'', "''"))
}

async fn sqlite_schema(pool: &AnyPool) -> BTreeMap<String, TableSchema> {
    let tables: Vec<String> =
        sqlx::query_scalar("SELECT name FROM sqlite_master WHERE type = 'table'")
            .fetch_all(pool)
            .await
            .expect("list the SQLite tables");
    let mut schema = BTreeMap::new();
    for table in tables.into_iter().filter(|name| !is_internal(name)) {
        schema.insert(table.clone(), sqlite_table(pool, &table).await);
    }
    schema
}

async fn sqlite_table(pool: &AnyPool, table: &str) -> TableSchema {
    let rows = sqlx::query(&format!(
        "SELECT name, type, \"notnull\", dflt_value, pk FROM pragma_table_info({}) ORDER BY cid",
        quoted(table)
    ))
    .fetch_all(pool)
    .await
    .unwrap_or_else(|error| panic!("describe the SQLite table {table}: {error}"));

    let mut columns = Vec::new();
    let mut keyed: Vec<(i64, String)> = Vec::new();
    for row in rows {
        let name: String = row.try_get("name").expect("a column name");
        let declared: String = row
            .try_get::<Option<String>, _>("type")
            .expect("a declared type")
            .unwrap_or_default();
        let not_null: i64 = row.try_get("notnull").expect("the not-null flag");
        let default: Option<String> = row.try_get("dflt_value").expect("a column default");
        let position: i64 = row.try_get("pk").expect("the primary-key position");
        columns.push(Column {
            name: name.clone(),
            type_class: sqlite_type_class(&declared),
            // A primary-key column is never null on either backend, even where
            // SQLite leaves the not-null flag clear.
            not_null: not_null != 0 || position > 0,
            has_default: default.is_some(),
        });
        if position > 0 {
            keyed.push((position, name));
        }
    }
    keyed.sort();

    let mut indexes = BTreeSet::new();
    let lists = sqlx::query(&format!(
        "SELECT name, \"unique\" AS is_unique, origin FROM pragma_index_list({}) ORDER BY seq",
        quoted(table)
    ))
    .fetch_all(pool)
    .await
    .unwrap_or_else(|error| panic!("list the SQLite indexes of {table}: {error}"));
    for row in lists {
        let name: String = row.try_get("name").expect("an index name");
        let unique: i64 = row.try_get("is_unique").expect("the unique flag");
        let origin: Option<String> = row.try_get("origin").expect("the index origin");
        // The primary key is compared on its own.
        if origin.as_deref() == Some("pk") {
            continue;
        }
        let members: Vec<String> = sqlx::query(&format!(
            "SELECT name FROM pragma_index_info({}) ORDER BY seqno",
            quoted(&name)
        ))
        .fetch_all(pool)
        .await
        .unwrap_or_else(|error| panic!("describe the SQLite index {name}: {error}"))
        .into_iter()
        .map(|member| {
            member
                .try_get::<Option<String>, _>("name")
                .expect("an index column")
                .unwrap_or_else(|| "<expression>".to_owned())
        })
        .collect();
        indexes.insert(index_signature(unique != 0, &members));
    }

    let mut foreign_keys = BTreeSet::new();
    let lists = sqlx::query(&format!(
        "SELECT \"table\" AS references_table, \"from\" AS from_column, \"to\" AS to_column, \
         on_delete FROM pragma_foreign_key_list({}) ORDER BY id, seq",
        quoted(table)
    ))
    .fetch_all(pool)
    .await
    .unwrap_or_else(|error| panic!("list the SQLite foreign keys of {table}: {error}"));
    for row in lists {
        let references_table: String = row.try_get("references_table").expect("a referenced table");
        let from_column: String = row.try_get("from_column").expect("a referencing column");
        let to_column: Option<String> = row.try_get("to_column").expect("a referenced column");
        let on_delete: Option<String> = row.try_get("on_delete").expect("an on-delete action");
        foreign_keys.insert(foreign_key_signature(
            &from_column,
            &references_table,
            to_column.as_deref().unwrap_or("<primary key>"),
            on_delete.as_deref().unwrap_or("NO ACTION"),
        ));
    }

    let definition: String =
        sqlx::query_scalar("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = $1")
            .bind(table)
            .fetch_one(pool)
            .await
            .unwrap_or_else(|error| panic!("read the SQLite definition of {table}: {error}"));

    let triggers: BTreeSet<String> = sqlx::query_scalar(
        "SELECT name FROM sqlite_master WHERE type = 'trigger' AND tbl_name = $1 ORDER BY name",
    )
    .bind(table)
    .fetch_all(pool)
    .await
    .unwrap_or_else(|error| panic!("list the SQLite triggers of {table}: {error}"))
    .into_iter()
    .collect();

    TableSchema {
        columns,
        primary_key: keyed.into_iter().map(|(_, name)| name).collect(),
        indexes,
        foreign_keys,
        checks: count_check_constraints(&definition),
        triggers,
    }
}

/// Count the `CHECK` constraints declared in a SQLite table definition.
///
/// Migrations spell the keyword both as `CHECK (` and as `CHECK(`, so the count
/// tolerates any amount of whitespace between the keyword and its parenthesis.
fn count_check_constraints(definition: &str) -> usize {
    let upper = definition.to_ascii_uppercase();
    let mut count = 0;
    let mut rest = upper.as_str();
    while let Some(position) = rest.find("CHECK") {
        rest = &rest[position + "CHECK".len()..];
        if rest.trim_start().starts_with('(') {
            count += 1;
        }
    }
    count
}

fn sqlite_type_class(declared: &str) -> &'static str {
    match declared.trim().to_ascii_uppercase().as_str() {
        "TEXT" => "text",
        "INTEGER" => "integer",
        "REAL" => "real",
        "BLOB" => "blob",
        other => panic!("the SQLite schema declares the unknown column type {other:?}"),
    }
}

fn index_signature(unique: bool, members: &[String]) -> String {
    format!(
        "{}({})",
        if unique { "unique" } else { "index" },
        members.join(", ")
    )
}

fn foreign_key_signature(
    from_column: &str,
    references_table: &str,
    to_column: &str,
    on_delete: &str,
) -> String {
    format!("{from_column} -> {references_table}.{to_column} on delete {on_delete}")
}

async fn postgres_schema(pool: &AnyPool) -> BTreeMap<String, TableSchema> {
    let tables: Vec<String> = sqlx::query_scalar(
        "SELECT table_name::text FROM information_schema.tables \
         WHERE table_schema = current_schema() AND table_type = 'BASE TABLE'",
    )
    .fetch_all(pool)
    .await
    .expect("list the PostgreSQL tables");
    let mut schema = BTreeMap::new();
    for table in tables.into_iter().filter(|name| !is_internal(name)) {
        schema.insert(table.clone(), postgres_table(pool, &table).await);
    }
    schema
}

async fn postgres_table(pool: &AnyPool, table: &str) -> TableSchema {
    let rows = sqlx::query(
        "SELECT column_name::text AS name, data_type::text AS declared, \
                (is_nullable = 'NO')::int AS not_null, \
                (column_default IS NOT NULL AND is_identity = 'NO')::int AS has_default \
         FROM information_schema.columns \
         WHERE table_schema = current_schema() AND table_name = $1 \
         ORDER BY ordinal_position",
    )
    .bind(table)
    .fetch_all(pool)
    .await
    .unwrap_or_else(|error| panic!("describe the PostgreSQL table {table}: {error}"));
    let mut columns = Vec::new();
    for row in rows {
        let name: String = row.try_get("name").expect("a column name");
        let declared: String = row.try_get("declared").expect("a declared type");
        let not_null: i64 = row.try_get("not_null").expect("the not-null flag");
        let has_default: i64 = row.try_get("has_default").expect("the default flag");
        columns.push(Column {
            name,
            type_class: postgres_type_class(&declared),
            not_null: not_null != 0,
            has_default: has_default != 0,
        });
    }

    let primary_key: Vec<String> = sqlx::query_scalar(
        "SELECT kcu.column_name::text \
         FROM information_schema.table_constraints tc \
         JOIN information_schema.key_column_usage kcu \
           ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema \
         WHERE tc.table_schema = current_schema() AND tc.table_name = $1 \
           AND tc.constraint_type = 'PRIMARY KEY' \
         ORDER BY kcu.ordinal_position",
    )
    .bind(table)
    .fetch_all(pool)
    .await
    .unwrap_or_else(|error| panic!("read the PostgreSQL primary key of {table}: {error}"));

    let mut indexes = BTreeSet::new();
    let mut current: Option<(String, bool, Vec<String>)> = None;
    let rows = sqlx::query(
        "SELECT idx.relname::text AS index_name, i.indisunique::int AS is_unique, \
                a.attname::text AS column_name \
         FROM pg_index i \
         JOIN pg_class t ON t.oid = i.indrelid \
         JOIN pg_namespace n ON n.oid = t.relnamespace \
         JOIN pg_class idx ON idx.oid = i.indexrelid \
         LEFT JOIN LATERAL unnest(i.indkey) WITH ORDINALITY AS key (attnum, position) ON true \
         LEFT JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = key.attnum \
         WHERE n.nspname = current_schema() AND t.relname = $1 AND NOT i.indisprimary \
         ORDER BY index_name, position",
    )
    .bind(table)
    .fetch_all(pool)
    .await
    .unwrap_or_else(|error| panic!("list the PostgreSQL indexes of {table}: {error}"));
    for row in rows {
        let name: String = row.try_get("index_name").expect("an index name");
        let unique: i64 = row.try_get("is_unique").expect("the unique flag");
        let member: Option<String> = row.try_get("column_name").expect("an index column");
        let member = member.unwrap_or_else(|| "<expression>".to_owned());
        match current.take() {
            Some((open_name, open_unique, mut members)) if open_name == name => {
                members.push(member);
                current = Some((open_name, open_unique, members));
            }
            Some((open_name, open_unique, members)) => {
                indexes.insert(index_signature(open_unique, &members));
                let _ = open_name;
                current = Some((name, unique != 0, vec![member]));
            }
            None => current = Some((name, unique != 0, vec![member])),
        }
    }
    if let Some((_, unique, members)) = current {
        indexes.insert(index_signature(unique, &members));
    }

    let mut foreign_keys = BTreeSet::new();
    // Pair each referencing column with the referenced column at the same
    // ordinal position. Joining `constraint_column_usage` pairs every
    // referencing column with every referenced column of a composite key, which
    // invents foreign keys that do not exist.
    let rows = sqlx::query(
        "SELECT a.attname::text AS from_column, ft.relname::text AS references_table, \
                fa.attname::text AS to_column, \
                CASE c.confdeltype \
                    WHEN 'a' THEN 'NO ACTION' WHEN 'r' THEN 'RESTRICT' \
                    WHEN 'c' THEN 'CASCADE' WHEN 'n' THEN 'SET NULL' \
                    WHEN 'd' THEN 'SET DEFAULT' ELSE c.confdeltype::text \
                END AS on_delete \
         FROM pg_constraint c \
         JOIN pg_class t ON t.oid = c.conrelid \
         JOIN pg_namespace n ON n.oid = t.relnamespace \
         JOIN pg_class ft ON ft.oid = c.confrelid \
         JOIN LATERAL unnest(c.conkey) WITH ORDINALITY AS k (attnum, position) ON true \
         JOIN LATERAL unnest(c.confkey) WITH ORDINALITY AS f (attnum, position) \
           ON f.position = k.position \
         JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = k.attnum \
         JOIN pg_attribute fa ON fa.attrelid = ft.oid AND fa.attnum = f.attnum \
         WHERE n.nspname = current_schema() AND t.relname = $1 AND c.contype = 'f'",
    )
    .bind(table)
    .fetch_all(pool)
    .await
    .unwrap_or_else(|error| panic!("list the PostgreSQL foreign keys of {table}: {error}"));
    for row in rows {
        let from_column: String = row.try_get("from_column").expect("a referencing column");
        let references_table: String = row.try_get("references_table").expect("a referenced table");
        let to_column: String = row.try_get("to_column").expect("a referenced column");
        let on_delete: String = row.try_get("on_delete").expect("an on-delete action");
        foreign_keys.insert(foreign_key_signature(
            &from_column,
            &references_table,
            &to_column,
            &on_delete,
        ));
    }

    // `contype = 'c'` is a CHECK constraint; `contype = 'n'` (PostgreSQL 18 and
    // later) is the NOT NULL constraint that SQLite stores as a column flag.
    let checks: i64 = sqlx::query_scalar(
        "SELECT count(*)::int8 FROM pg_constraint \
         WHERE contype = 'c' AND conrelid = ( \
             SELECT c.oid FROM pg_class c \
             JOIN pg_namespace n ON n.oid = c.relnamespace \
             WHERE n.nspname = current_schema() AND c.relname = $1)",
    )
    .bind(table)
    .fetch_one(pool)
    .await
    .unwrap_or_else(|error| panic!("count the PostgreSQL CHECK constraints of {table}: {error}"));

    let triggers: BTreeSet<String> = sqlx::query_scalar(
        "SELECT tg.tgname::text FROM pg_trigger tg \
         JOIN pg_class c ON c.oid = tg.tgrelid \
         JOIN pg_namespace n ON n.oid = c.relnamespace \
         WHERE n.nspname = current_schema() AND c.relname = $1 AND NOT tg.tgisinternal",
    )
    .bind(table)
    .fetch_all(pool)
    .await
    .unwrap_or_else(|error| panic!("list the PostgreSQL triggers of {table}: {error}"))
    .into_iter()
    .collect();

    TableSchema {
        columns,
        primary_key,
        indexes,
        foreign_keys,
        checks: usize::try_from(checks).expect("a non-negative CHECK constraint count"),
        triggers,
    }
}

fn postgres_type_class(declared: &str) -> &'static str {
    match declared {
        "text" | "character varying" | "character" => "text",
        "bigint" | "integer" | "smallint" => "integer",
        "double precision" | "real" => "real",
        "bytea" => "blob",
        other => panic!("the PostgreSQL schema declares the unknown column type {other:?}"),
    }
}
