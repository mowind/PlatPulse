#!/usr/bin/env python3
"""Spike #253: mechanically translate the current Server SQLite schema into a
PostgreSQL schema that mirrors the SQLite logical column types (ADR 0013).

Throwaway helper. It is NOT the S4 migration baseline: triggers are skipped
and reported, and the output only needs to be good enough to run the
Report Ingestion slice of the sqlx::Any spike against a real PostgreSQL.

Usage: translate_schema.py <sqlite.db> > pg_schema.sql
"""
import re
import sqlite3
import sys

TYPE_RULES = [
    # rowid alias -> identity; keeps RETURNING and explicit inserts working.
    (re.compile(r"\bINTEGER PRIMARY KEY\b"), "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    (re.compile(r"\bINTEGER\b"), "BIGINT"),
    (re.compile(r"\bREAL\b"), "DOUBLE PRECISION"),
    (re.compile(r"\bBLOB\b"), "BYTEA"),
    (re.compile(r"\bTEXT\b"), 'TEXT COLLATE "C"'),
]
GLOB = re.compile(r"(\w+) GLOB '\[A-Z\]\[A-Z\]'")


def translate_table(sql: str) -> str:
    out = sql
    for pattern, replacement in TYPE_RULES:
        out = pattern.sub(replacement, out)
    out = GLOB.sub(r"\1 ~ '^[A-Z][A-Z]$'", out)
    return out


def main() -> None:
    db = sqlite3.connect(sys.argv[1])
    rows = db.execute(
        "SELECT type, name, sql FROM sqlite_master "
        "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name <> '_sqlx_migrations' "
        "ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, rowid"
    ).fetchall()
    tables = [(n, s) for t, n, s in rows if t == "table"]
    indexes = [(n, s) for t, n, s in rows if t == "index"]
    skipped = [n for t, n, _ in rows if t not in ("table", "index")]
    print("-- Generated by tests/any_spike/translate_schema.py (spike #253, throwaway).")
    print("-- Skipped (need PL/pgSQL rewrite in S4): " + ", ".join(skipped))
    # Foreign keys may point at tables created later in sqlite_master order;
    # emit tables in dependency order so PostgreSQL accepts inline REFERENCES.
    remaining = dict(tables)
    emitted = set()
    while remaining:
        progress = False
        for name, sql in list(remaining.items()):
            refs = set(re.findall(r"REFERENCES\s+(\w+)", sql)) - {name}
            if refs <= emitted:
                print(translate_table(sql) + ";\n")
                emitted.add(name)
                del remaining[name]
                progress = True
        if not progress:
            raise SystemExit("cyclic foreign keys: " + ", ".join(remaining))
    for _, sql in indexes:
        print(sql + ";\n")


if __name__ == "__main__":
    main()
