#!/usr/bin/env python3
"""Issue #212 Story 46 baseline: capacity and performance for two Agents and six Nodes.

This script produces a *measured baseline*, not a production capacity promise.
Story 46 asks for a capacity and performance report with explicit sampling,
mount and hardware conditions, so every number in the output is tied to

  * the exact Server binary built from this checkout,
  * the filesystem the temporary state directory actually lives on,
  * the declared Agent cadence (a fast path plus a much slower scan), and
  * the observed low-space protection state machine on real database rows.

The Server is driven through its real surfaces: the production binary, the
real Owner login and Admin API, real Agent Enrollment over the Agent HTTP
surface, real Report ingestion into a temporary SQLite database, and real
capacity protection transitions produced by rewriting the deployment policy
and restarting the process. Reports are generated by a deterministic load
generator seeded from --seed; that substitution, the retention window and the
missing history family are listed under "not_delivered" instead of being
extrapolated into a guarantee.

Usage:
    python3 scripts/capacity-baseline.py --output-root target/capacity-baseline
"""

