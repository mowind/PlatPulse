class Client:
    """Minimal HTTP client shaped like scripts/release-qualification.py."""

    def __init__(self, port: int, timeout: float) -> None:
        self.port = port
        self.timeout = timeout

    def request(self, method: str, path: str, *, body: bytes | None = None, headers: dict | None = None):
        started = time.monotonic()
        connection = http.client.HTTPConnection("127.0.0.1", self.port, timeout=self.timeout)
        try:
            connection.request(method, path, body=body, headers=headers or {})
            response = connection.getresponse()
            payload = response.read()
            elapsed = (time.monotonic() - started) * 1000
            return response.status, {key.lower(): value for key, value in response.getheaders()}, payload, elapsed
        finally:
            connection.close()


class ServerProcess:
    """The packaged Server under test, started with its deployment config."""

    def __init__(self, binary: Path, config: Path, log_path: Path, port: int, timeout: float) -> None:
        self.binary = binary
        self.config = config
        self.log_path = log_path
        self.port = port
        self.timeout = timeout
        self.process: subprocess.Popen | None = None
        self.log_handle = None

    def start(self) -> None:
        global SERVER_RUNNING
        self.log_handle = self.log_path.open("a", encoding="utf-8")
        self.log_handle.write("\n=== baseline start " + utc_now() + " ===\n")
        self.log_handle.flush()
        self.process = subprocess.Popen(
            [str(self.binary), "serve", "--config", str(self.config)],
            cwd=str(ROOT),
            stdout=self.log_handle,
            stderr=subprocess.STDOUT,
            text=True,
        )
        client = Client(self.port, self.timeout)
        live = False
        for _ in range(200):
            if self.process.poll() is not None:
                raise BaselineError("Server exited during startup; see " + str(self.log_path))
            try:
                status, _, _, _ = client.request("GET", "/health/live")
                if status == 200:
                    live = True
                    break
            except OSError:
                pass
            time.sleep(0.1)
        if not live:
            raise BaselineError("Server did not become live")
        for _ in range(200):
            try:
                status, _, _, _ = client.request("GET", "/health/ready")
                if status == 200:
                    SERVER_RUNNING = True
                    return
            except OSError:
                pass
            time.sleep(0.1)
        raise BaselineError("Server did not become ready")

    def stop(self) -> None:
        global SERVER_RUNNING
        SERVER_RUNNING = False
        if self.process is None:
            return
        if self.process.poll() is None:
            self.process.send_signal(signal.SIGTERM)
            try:
                self.process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=5)
        if self.log_handle is not None:
            self.log_handle.close()
        self.process = None
        self.log_handle = None


