def baseline_block_hash(node_id: str, height: int) -> str:
    """A deterministic 32-byte block hash for a declared (Node, height)."""
    seed = node_id + ":" + str(height)
    return "0x" + hashlib.sha256(seed.encode("utf-8")).hexdigest()


