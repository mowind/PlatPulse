class BaselineError(RuntimeError):
    """The baseline run cannot continue with trustworthy numbers."""


class Check:
    """A self-check on the numbers the report publishes."""

    def __init__(self, name: str, expected, observed) -> None:
        self.name = name
        self.expected = expected
        self.observed = observed

    @property
    def ok(self) -> bool:
        return self.expected == self.observed

    def as_json(self) -> dict:
        return {"name": self.name, "expected": self.expected, "observed": self.observed, "ok": self.ok}


def json_safe(value):
    """Render a measured payload as the JSON it is published as.

    A check may hold a set of tuples, or a dict keyed by a tuple, to compare a
    measurement the way the database groups it. That compares fine in memory but
    JSON cannot carry it, so the published report states such a payload as the
    list of its items and the printed form of its keys instead of failing to
    serialise the whole report."""
    if isinstance(value, dict):
        return {
            key if isinstance(key, str) else str(key): json_safe(item)
            for key, item in value.items()
        }
    if isinstance(value, (set, frozenset)):
        return sorted((json_safe(item) for item in value), key=repr)
    if isinstance(value, (list, tuple)):
        return [json_safe(item) for item in value]
    return value


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def advance_timestamp(previous: str | None) -> str:
    """Never reuse a second already used for a sample primary key."""
    # The cursor is a whole second, so the guard has to compare whole seconds:
    # a clock a fraction of a second past the last instant still formats to the
    # same string, and delivering that instant twice would offer the Server a
    # second observation of a sample it already counted, which it classifies as
    # a replay rather than as another lost sample. Truncating first makes the
    # comparison exact.
    now = datetime.now(timezone.utc).replace(microsecond=0)
    if previous is not None:
        last = datetime.strptime(previous, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
        if now <= last:
            now = last + timedelta(seconds=1)
    return now.strftime("%Y-%m-%dT%H:%M:%SZ")


def command(args, *, input_text: str | None = None, timeout: float = 900, cwd: Path = ROOT):
    completed = subprocess.run(
        [str(item) for item in args],
        input=input_text,
        capture_output=True,
        text=True,
        cwd=str(cwd),
        timeout=timeout,
        check=False,
    )
    if completed.returncode != 0:
        raise BaselineError(
            "command failed with status "
            + str(completed.returncode)
            + ": "
            + " ".join(str(item) for item in args)
            + "\n"
            + completed.stderr.strip()[:2000]
        )
    return completed


def free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.bind(("127.0.0.1", 0))
        return int(probe.getsockname()[1])


def json_bytes(value) -> bytes:
    return json.dumps(value, separators=(",", ":"), sort_keys=True).encode("utf-8")


def percentile(values: list[float], fraction: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    if len(ordered) == 1:
        return ordered[0]
    position = fraction * (len(ordered) - 1)
    lower = int(position)
    upper = min(lower + 1, len(ordered) - 1)
    weight = position - lower
    return ordered[lower] * (1 - weight) + ordered[upper] * weight


def human_bytes(value: int | None) -> str:
    if value is None:
        return "unknown"
    size = float(value)
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if size < 1024 or unit == "TiB":
            return f"{size:.2f} {unit}"
        size /= 1024
    return f"{size:.2f} TiB"


def filesystem_sample(path: Path) -> dict:
    stat = os.statvfs(str(path))
    unit = stat.f_frsize or stat.f_bsize
    return {
        "path": str(path),
        "fragment_size": unit,
        "total_bytes": unit * stat.f_blocks,
        "available_bytes": unit * stat.f_bavail,
        "free_bytes": unit * stat.f_bfree,
    }


def mount_conditions(path: Path) -> dict:
    resolved = str(path.resolve())
    best: tuple[str, str, str] | None = None
    for line in Path("/proc/mounts").read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) < 3:
            continue
        point, filesystem_type = parts[1], parts[2]
        if resolved == point or resolved.startswith(point.rstrip("/") + "/"):
            if best is None or len(point) > len(best[0]):
                best = (point, filesystem_type, parts[0])
    if best is None:
        return {"mount_point": None, "filesystem_type": None, "mount_source": None}
    return {"mount_point": best[0], "filesystem_type": best[1], "mount_source": best[2]}


def hardware_conditions() -> dict:
    uname = os.uname()
    cpu_model = None
    cpuinfo = Path("/proc/cpuinfo")
    if cpuinfo.is_file():
        for line in cpuinfo.read_text(encoding="utf-8").splitlines():
            if line.lower().startswith("model name"):
                cpu_model = line.split(":", 1)[1].strip()
                break
    memory_total = None
    meminfo = Path("/proc/meminfo")
    if meminfo.is_file():
        for line in meminfo.read_text(encoding="utf-8").splitlines():
            if line.startswith("MemTotal:"):
                memory_total = int(line.split()[1]) * 1024
                break
    return {
        "kernel": uname.sysname + " " + uname.release,
        "machine": uname.machine,
        "cpu_model": cpu_model,
        "cpu_cores": os.cpu_count(),
        "memory_total_bytes": memory_total,
        "python_version": sys.version.split()[0],
    }


