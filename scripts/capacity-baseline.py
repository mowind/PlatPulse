def enroll_agent(token: str, client: Client, agent_index: int) -> dict:
    """Real Agent Enrollment over the Agent HTTP surface.

    Enrollment carries no request body, so it uses curl exactly like
    scripts/release-qualification.py does.
    """
    url = "http://127.0.0.1:" + str(client.port) + "/api/agent/v1/enroll"
    completed = subprocess.run(
        [
            "curl",
            "-sS",
            "--connect-timeout",
            "2",
            "--max-time",
            str(client.timeout),
            "-H",
            "Authorization: Bearer " + token,
            "-X",
            "POST",
            url,
            "-w",
            "\n%{http_code}",
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        raise BaselineError("Agent Enrollment transport failed: " + completed.stderr.strip()[:400])
    body, status_text = completed.stdout.rsplit("\n", 1)
    if int(status_text) != 200:
        raise BaselineError("Agent Enrollment failed with status " + status_text + ": " + body.strip()[:400])
    payload = json.loads(body)
    return {
        "agent_index": agent_index,
        "agent_id": payload["agent_id"],
        "agent_epoch": int(payload["agent_epoch"]),
        "credential": payload["credential"],
        "boot_id": str(uuid.uuid4()),
    }


def agent_diagnostics(client: Client, cookie: str) -> list:
    """Agents the running Server itself reports, read over HTTP.

    This is how the baseline confirms Server-side state while the Server
    runs: it must not attach an external SQLite connection.
    """
    status, _, payload, _ = admin_get(client, cookie, "/api/admin/v1/agents")
    if status != 200:
        raise BaselineError("GET /api/admin/v1/agents failed with status " + str(status))
    body = json.loads(payload)
    return body if isinstance(body, list) else body.get("agents", [])


