def recursive_replace(value, replacements: dict):
    if isinstance(value, dict):
        return {key: recursive_replace(item, replacements) for key, item in value.items()}
    if isinstance(value, list):
        return [recursive_replace(item, replacements) for item in value]
    if isinstance(value, str):
        return replacements.get(value, value)
    return value


def bump_observation_revisions(value, increment: int, observed_at: str) -> None:
    """Age every observation in the payload so each Report is a fresh one."""
    if isinstance(value, dict):
        for key in ("state_revision", "value_revision"):
            if isinstance(value.get(key), int):
                value[key] = value[key] + increment
        for key in ("attempted_at", "latest_observed_at", "observed_at"):
            if isinstance(value.get(key), str):
                value[key] = observed_at
        for item in value.values():
            bump_observation_revisions(item, increment, observed_at)
    elif isinstance(value, list):
        for item in value:
            bump_observation_revisions(item, increment, observed_at)


def observation(latest, observed_at: str) -> dict:
    return {
        "status": "ok",
        "attempted_at": observed_at,
        "latest_observed_at": observed_at,
        "state_revision": 1,
        "value_revision": 1,
        "latest": latest,
    }


def peer_component(observed_at: str, inbound: int, outbound: int, sequence: int) -> dict:
    peers = []
    for index in range(inbound + outbound):
        direction = "inbound" if index < inbound else "outbound"
        peers.append(
            {
                "peer_id": "baseline-peer-" + direction + "-" + str(index + 1),
                "remote_ip": "203.0.113." + str(10 + index),
                "direction": direction,
                "trusted": index % 2 == 0,
                "static_peer": False,
                "consensus_peer": True,
                "client_name": "PlatON/v1.4.0",
                "caps": ["cbft/1", "platon/1"],
                "cbft_protocol_version": 1,
                "cbft_highest_qc_block": 100000 + sequence * 10 + index,
                "cbft_locked_block": 99999 + sequence * 10 + index,
                "cbft_commit_block": 99998 + sequence * 10 + index,
            }
        )
    return observation({"peers": peers}, observed_at)


def baseline_block_hash(node_id: str, height: int) -> str:
    """A deterministic 32-byte block hash for a declared (Node, height)."""
    seed = node_id + ":" + str(height)
    return "0x" + hashlib.sha256(seed.encode("utf-8")).hexdigest()


