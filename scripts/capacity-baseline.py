def build_report(
    template: dict,
    minimal: dict,
    *,
    identity: dict,
    sequence: int,
    observed_at: str,
    node_ids: list[str],
    agent_index: int,
    head_base: int,
    slow_scan: bool,
    rng: random.Random,
) -> dict:
    report = copy.deepcopy(template)
    report["agent_id"] = identity["agent_id"]
    report["agent_epoch"] = identity["agent_epoch"]
    report["boot_id"] = identity["boot_id"]
    report["report_id"] = str(uuid.uuid4())
    report["report_sequence"] = sequence
    report["generated_at"] = observed_at

    # The canonical fixture carries host components in error states, so the
    # baseline host payload starts from the fixture whose host is fully ok:
    # that is what makes the generic writer persist host network history.
    report["host"] = copy.deepcopy(minimal["host"])
    report["host"]["cpu_percent"] = observation(round(rng.uniform(4.0, 55.0), 2), observed_at)
    report["host"]["memory"] = observation(
        {"total_bytes": 17179869184, "used_bytes": int(4.5e9 + rng.uniform(0.0, 2.0e9))}, observed_at
    )
    report["host"]["network_throughput"] = observation(
        {
            "rx_bytes_per_sec": int(rng.uniform(20000.0, 900000.0)),
            "tx_bytes_per_sec": int(rng.uniform(10000.0, 400000.0)),
        },
        observed_at,
    )

    base_nodes = template["nodes"]
    nodes = []
    inventory = []
    for index, node_id in enumerate(node_ids):
        source = base_nodes[index % len(base_nodes)]
        node = recursive_replace(copy.deepcopy(source), {source["node_id"]: node_id})
        # Every baseline Node runs a live Validator process, so all six Nodes
        # contribute the same optional Node series every round.
        node["process"] = copy.deepcopy(base_nodes[0]["process"])
        sync = node.get("chain", {}).get("sync", {}).get("latest")
        if isinstance(sync, dict):
            sync["current_block"] = head_base + index
            sync["highest_block"] = max(int(sync.get("highest_block", 0)), head_base + index)
        if slow_scan:
            node["data_directory_size_bytes"] = observation(int(6.5e11 + rng.uniform(0.0, 5.0e8)), observed_at)
            node["data_directory_capacity_bytes"] = observation(1099511627776, observed_at)
            node["chain"]["peers"] = peer_component(observed_at, 2, 2, sequence)
        else:
            node.pop("data_directory_size_bytes", None)
            node.pop("data_directory_capacity_bytes", None)
            node["chain"].pop("peers", None)
        nodes.append(node)
        inventory.append(
            {
                "node_id": node_id,
                "display_name": "Baseline Node " + str(agent_index + 1) + "-" + str(index + 1),
                "network_key": NETWORK["networkKey"],
                "rpc_endpoint": "ws://127.0.0.1:" + str(6790 + agent_index * 10 + index),
            }
        )

    # The canonical fixture declares two Nodes, so its Block Summaries and
    # History Gaps reference Node IDs this Report replaces. Remap them with the
    # same index-modulo rule used to build the Node set (the rule
    # scripts/release-qualification.py already proves), because the Server
    # rejects a Report whose entries reference an undeclared Node.
    fixture_nodes = [item["node_id"] for item in template["inventory"]["nodes"]]
    node_mapping = {old: node_ids[index % len(node_ids)] for index, old in enumerate(fixture_nodes)}
    # A live Node advances its chain every round, so the baseline shifts the
    # fixture heights with the round instead of replaying fixed ones: a sample
    # at or below the retained high-water mark answers "resync_replay" and the
    # receipt would read partially_accepted for a reason this measurement is
    # not about. Hashes follow the shifted height so no height is ever claimed
    # with two different hashes.
    blocks = recursive_replace(copy.deepcopy(template["block_summaries"]), node_mapping)
    first_height = head_base - len(blocks)
    observed_ms = int(datetime.fromisoformat(observed_at.replace("Z", "+00:00")).timestamp() * 1000)
    for offset, block in enumerate(blocks):
        height = first_height + offset
        block["block_number"] = height
        block["block_hash"] = baseline_block_hash(block["node_id"], height)
        block["parent_hash"] = baseline_block_hash(block["node_id"], height - 1)
        block["block_timestamp_ms"] = observed_ms - (len(blocks) - offset) * 2000
        block["observed_at"] = observed_at
        if block.get("source") == "gap_backfill":
            block["source"] = "subscription"
        block.pop("block_interval_ms", None)
    report["block_summaries"] = blocks
    report["history_gaps"] = recursive_replace(report["history_gaps"], node_mapping)

    report["nodes"] = nodes
    report["inventory"] = {"revision": sequence, "nodes": inventory}
    bump_observation_revisions(report, sequence - 1, observed_at)
    return report


CORE_TABLES = (
    "agent_report_receipts",
    "current_host_observations",
    "current_node_process_observations",
    "current_node_chain_observations",
    "agents",
    "nodes",
)


def core_counts(db_path: Path) -> dict:
    return {table: sqlite_scalar(db_path, "SELECT COUNT(*) FROM " + table) for table in CORE_TABLES}


def optional_counts(db_path: Path) -> dict:
    return {
        "host_samples": sqlite_scalar(db_path, "SELECT COUNT(*) FROM host_metric_samples"),
        "node_samples": sqlite_scalar(db_path, "SELECT COUNT(*) FROM node_metric_samples"),
        "host_series": sqlite_scalar(
            db_path, "SELECT COUNT(*) FROM (SELECT DISTINCT agent_id, metric FROM host_metric_samples)"
        ),
        "node_series": sqlite_scalar(
            db_path, "SELECT COUNT(*) FROM (SELECT DISTINCT node_id, metric FROM node_metric_samples)"
        ),
        "host_by_metric": sqlite_rows(
            db_path,
            "SELECT metric, COUNT(*) AS samples, COUNT(DISTINCT agent_id) AS scopes "
            "FROM host_metric_samples GROUP BY metric ORDER BY metric",
        ),
        "node_by_metric": sqlite_rows(
            db_path,
            "SELECT metric, COUNT(*) AS samples, COUNT(DISTINCT node_id) AS scopes "
            "FROM node_metric_samples GROUP BY metric ORDER BY metric",
        ),
        "node_rows_per_series": sqlite_rows(
            db_path,
            "SELECT COUNT(*) AS series, MIN(samples) AS least, MAX(samples) AS most, "
            "AVG(samples) AS mean FROM (SELECT COUNT(*) AS samples FROM node_metric_samples GROUP BY node_id, metric)",
        ),
        "host_rows_per_series": sqlite_rows(
            db_path,
            "SELECT COUNT(*) AS series, MIN(samples) AS least, MAX(samples) AS most, "
            "AVG(samples) AS mean FROM (SELECT COUNT(*) AS samples FROM host_metric_samples GROUP BY agent_id, metric)",
        ),
    }


def storage_bytes(db_path: Path) -> dict:
    return {
        "database_bytes": file_bytes(db_path),
        "wal_bytes": file_bytes(db_path.with_name(db_path.name + "-wal")),
        "shm_bytes": file_bytes(db_path.with_name(db_path.name + "-shm")),
    }


def larger_storage(left: dict, right: dict) -> dict:
    "Element-wise maximum: the largest live reading of a file that also shrinks."
    return {key: max(left[key], right[key]) for key in left}


def capacity_state(client: Client, cookie: str) -> dict:
    status, _, payload, elapsed = admin_get(client, cookie, "/api/admin/v1/capacity")
    if status != 200:
        raise BaselineError("GET /api/admin/v1/capacity failed with status " + str(status))
    body = json.loads(payload)
    intervals = body.get("recentIntervals") or []
    return {
        "elapsed_ms": round(elapsed, 2),
        "enabled": body["enabled"],
        "protected": body["protected"],
        "pause_below_bytes": body["pauseBelowBytes"],
        "resume_above_bytes": body["resumeAboveBytes"],
        "sample_interval_seconds": body["sampleIntervalSeconds"],
        "policy_origin": body["policyOrigin"],
        "mount_path": body["mountPath"],
        "sampled_at": body["sampledAt"],
        "available_bytes": (body.get("sample") or {}).get("availableBytes"),
        "total_bytes": (body.get("sample") or {}).get("totalBytes"),
        "active_interval_id": body["activeIntervalId"],
        "sampling_error": body["samplingError"],
        "transition_error": body["transitionError"],
        "recent_intervals": intervals[:3],
    }


def measure_reads(client: Client, cookie: str, samples: int, metrics_client: Client) -> dict:
    measured = {}
    for name, path, use_metrics in (
        ("capacity", "/api/admin/v1/capacity", False),
        ("operations", "/api/admin/v1/operations?limit=50", False),
        ("metrics", "/metrics", True),
    ):
        latencies = []
        status_seen = None
        for _ in range(samples):
            if use_metrics:
                status, _, _, elapsed = metrics_client.request("GET", path)
            else:
                status, _, _, elapsed = admin_get(client, cookie, path)
            status_seen = status
            if status != 200:
                break
            latencies.append(elapsed)
        if not latencies:
            measured[name] = {"path": path, "samples": 0, "status": status_seen, "error": "not measured"}
            continue
        measured[name] = {
            "path": path,
            "status": status_seen,
            "samples": len(latencies),
            "p50_ms": round(percentile(latencies, 0.5), 2),
            "p95_ms": round(percentile(latencies, 0.95), 2),
            "min_ms": round(min(latencies), 2),
            "max_ms": round(max(latencies), 2),
        }
    return measured


def capacity_gauges(client: Client) -> list[str]:
    status, _, payload, _ = client.request("GET", "/metrics")
    if status != 200:
        return ["metrics endpoint returned status " + str(status)]
    text = payload.decode("utf-8", errors="replace")
    return [line for line in text.splitlines() if line.startswith("platpulse_capacity_")]


def skipped_series_rows(db_path: Path) -> list[dict]:
    return sqlite_rows(
        db_path,
        "SELECT scope_kind, scope_key, metric, skipped_count, first_skipped_at, last_skipped_at "
        "FROM capacity_skipped_series ORDER BY scope_kind, metric, scope_key",
    )


def interval_rows(db_path: Path) -> list[dict]:
    return sqlite_rows(
        db_path,
        "SELECT interval_id, source_mount, started_at, started_reason, opened_total_bytes, "
        "opened_available_bytes, pause_below_bytes, resume_above_bytes, ended_at, ended_reason, "
        "resumed_total_bytes, resumed_available_bytes FROM capacity_protection_intervals ORDER BY started_at",
    )


class BaselineRun:
    def __init__(self, args) -> None:
        self.args = args
        self.rng = random.Random(args.seed)
        self.run_root = args.output_root.resolve() / time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
        self.state_dir = self.run_root / "state"
        self.db_path = self.state_dir / "platpulse.db"
        self.pepper_path = self.state_dir / "server-pepper"
        self.config_path = self.run_root / "server.toml"
        self.log_path = self.run_root / "server.log"
        self.port = free_port()
        self.metrics_port = free_port()
        while self.metrics_port == self.port:
            self.metrics_port = free_port()
        self.binary = args.binary.resolve()
        self.web_root = args.web_root.resolve()
        self.client = Client(self.port, 30.0)
        self.metrics_client = Client(self.metrics_port, 30.0)
        self.server: ServerProcess | None = None
        self.cookie = ""
        self.csrf = ""
        self.agents: list[dict] = []
        self.node_ids = baseline_node_ids()
        self.sequences = [0, 0]
        self.observed_at: str | None = None
        self.checks: list[Check] = []
        self.report: dict = {}
        self.runtime_seconds = 0.0
        self.template: dict = {}
        self.minimal: dict = {}

    def write_policy(self, *, enabled: bool, pause: int | None, resume: int | None) -> None:
        write_config(
            self.config_path,
            state_dir=self.state_dir,
            db_path=self.db_path,
            pepper_path=self.pepper_path,
            web_root=self.web_root,
            port=self.port,
            metrics_port=self.metrics_port,
            capacity_enabled=enabled,
            pause_bytes=pause,
            resume_bytes=resume,
            sample_seconds=FAST_SAMPLE_SECONDS,
        )

    def start(self) -> None:
        self.server = ServerProcess(self.binary, self.config_path, self.log_path, self.port, 30.0)
        self.server.start()

    def stop(self) -> None:
        if self.server is not None:
            self.server.stop()
            self.server = None

    def next_timestamp(self) -> str:
        self.observed_at = advance_timestamp(self.observed_at)
        return self.observed_at

    def submit_round(self, *, slow_scan: bool, label: str) -> dict:
        observed_at = self.next_timestamp()
        head_base = 1_000_000 + self.sequences[0] * 5
        outcomes = []
        for index, agent in enumerate(self.agents):
            self.sequences[index] += 1
            report = build_report(
                self.template,
                self.minimal,
                identity=agent,
                sequence=self.sequences[index],
                observed_at=observed_at,
                node_ids=self.node_ids[index],
                agent_index=index,
                head_base=head_base,
                slow_scan=slow_scan,
                rng=self.rng,
            )
            status, payload, elapsed = send_report(self.client, agent["credential"], json_bytes(report))
            body = json.loads(payload) if payload else {}
            receipt = body.get("receipt") if isinstance(body.get("receipt"), dict) else {}
            outcomes.append(
                {
                    "agent_index": index,
                    "agent_id": agent["agent_id"],
                    "status": status,
                    "disposition": receipt.get("disposition"),
                    "receipt_id": receipt.get("report_id"),
                    "response": payload.decode("utf-8", errors="replace")[:400],
                    "elapsed_ms": round(elapsed, 2),
                }
            )
        rejected = [item for item in outcomes if item["status"] != 200]
        if rejected:
            raise BaselineError(label + " report submission failed: " + json.dumps(rejected))
        return {"label": label, "observed_at": observed_at, "slow_scan": slow_scan, "outcomes": outcomes}

    def steady_phase(self, baseline: dict) -> dict:
        "Measure the write path, then read the database with the Server stopped."
        # baseline carries the stopped-Server measurement taken just before the
        # first round, so this phase attaches an external SQLite connection
        # exactly once: after it has asked the Server to stop.
        rounds = self.args.rounds
        slow_rounds = [index for index in range(1, rounds + 1) if index % SLOW_SCAN_EVERY == 0]
        storage_before = baseline["storage"]
        started = time.monotonic()
        submissions: list[dict] = []
        # The WAL only exists while the Server runs: SQLite checkpoints and removes
        # it when the last connection closes, so a reading taken after the stop is
        # not the WAL this load produced. Sample the live files as the load runs.
        storage_peak = storage_bytes(self.db_path)
        for index in range(1, rounds + 1):
            submissions.append(self.submit_round(slow_scan=index in slow_rounds, label="steady round " + str(index)))
            storage_peak = larger_storage(storage_peak, storage_bytes(self.db_path))
            if index < rounds:
                time.sleep(self.args.interval)
        duration = time.monotonic() - started
        latencies = [item["elapsed_ms"] for submission in submissions for item in submission["outcomes"]]
        expected_samples = 0
        for index in range(1, rounds + 1):
            per_round = AGENT_COUNT * (len(HOST_METRICS) + NODES_PER_AGENT * len(STEADY_NODE_METRICS))
            if index in slow_rounds:
                per_round += AGENT_COUNT * NODES_PER_AGENT * len(SLOW_SCAN_NODE_METRICS)
            expected_samples += per_round
        capacity = capacity_state(self.client, self.cookie)
        reads = measure_reads(self.client, self.cookie, self.args.query_samples, self.metrics_client)
        # Read the loaded database and its WAL before stopping: this is the only
        # honest "after load" number. Stopping the Server and opening the database
        # with an external SQLite connection checkpoints the WAL away, which is how
        # an earlier revision of this script reported 0 bytes for a WAL that had
        # grown to megabytes.
        storage_after = storage_bytes(self.db_path)
        self.stop()
        storage_after_shutdown = storage_bytes(self.db_path)
        counts = optional_counts(self.db_path)
        core = core_counts(self.db_path)
        observed_samples = (
            counts["host_samples"]
            + counts["node_samples"]
            - baseline["optional"]["host_samples"]
            - baseline["optional"]["node_samples"]
        )
        host_samples = counts["host_samples"] - baseline["optional"]["host_samples"]
        receipts_added = core["agent_report_receipts"] - baseline["core"]["agent_report_receipts"]
        self.checks.append(Check("steady optional samples", expected_samples, observed_samples))
        self.checks.append(Check("steady host submissions", rounds * AGENT_COUNT, len(latencies)))
        self.checks.append(
            Check("steady host optional samples", rounds * AGENT_COUNT * len(HOST_METRICS), host_samples)
        )
        self.checks.append(Check("steady core receipts added", rounds * AGENT_COUNT, receipts_added))
        return {
            "rounds": rounds,
            "interval_seconds": self.args.interval,
            "slow_scan_every": SLOW_SCAN_EVERY,
            "slow_scan_rounds": slow_rounds,
            "duration_seconds": round(duration, 2),
            "submissions": len(latencies),
            "expected_optional_samples": expected_samples,
            "observed_optional_samples": observed_samples,
            "write_latency_ms": {
                "p50_ms": round(percentile(latencies, 0.5), 2),
                "p95_ms": round(percentile(latencies, 0.95), 2),
                "min_ms": round(min(latencies), 2),
                "max_ms": round(max(latencies), 2),
            },
            "throughput_submissions_per_second": round(len(latencies) / duration, 3) if duration > 0 else None,
            "host_optional_samples": host_samples,
            "receipts_added": receipts_added,
            "baseline_core_counts": baseline["core"],
            "baseline_optional_counts": baseline["optional"],
            "storage_before": storage_before,
            "storage_after": storage_after,
            "storage_peak": storage_peak,
            "storage_after_shutdown": storage_after_shutdown,
            "optional_counts": counts,
            "core_counts": core,
            "capacity": capacity,
            "read_path": reads,
        }

    def pressure_phase(self, steady_available_bytes: int) -> dict:
        self.stop()
        self.write_policy(enabled=True, pause=MAX_PERSISTED_BYTES, resume=MAX_PERSISTED_BYTES)
        core_before = core_counts(self.db_path)
        optional_before = optional_counts(self.db_path)
        self.start()
        observed = capacity_state(self.client, self.cookie)
        if not observed["protected"]:
            raise BaselineError("protection did not open under a pause floor above the mount")
        rounds = self.args.pressure_rounds
        submissions = []
        for index in range(1, rounds + 1):
            submissions.append(self.submit_round(slow_scan=False, label="pressure round " + str(index)))
            if index < rounds:
                time.sleep(1.0)
        capacity_after = capacity_state(self.client, self.cookie)
        gauges = capacity_gauges(self.metrics_client)
        self.stop()
        core_after = core_counts(self.db_path)
        optional_after = optional_counts(self.db_path)
        series_rows = skipped_series_rows(self.db_path)
        skipped_samples = sum(int(row["skipped_count"]) for row in series_rows)
        intervals = interval_rows(self.db_path)
        expected_samples = rounds * AGENT_COUNT * (len(HOST_METRICS) + NODES_PER_AGENT * len(STEADY_NODE_METRICS))
        self.checks.append(Check("pressure skipped samples", expected_samples, skipped_samples))
        self.checks.append(
            Check(
                "pressure optional samples unchanged",
                optional_before["host_samples"] + optional_before["node_samples"],
                optional_after["host_samples"] + optional_after["node_samples"],
            )
        )
        self.checks.append(
            Check(
                "pressure core receipts added",
                rounds * AGENT_COUNT,
                core_after["agent_report_receipts"] - core_before["agent_report_receipts"],
            )
        )
        return {
            "rounds": rounds,
            "mount_available_bytes": steady_available_bytes,
            "pause_below_bytes": MAX_PERSISTED_BYTES,
            "capacity_before": observed,
            "capacity_after": capacity_after,
            "capacity_gauges": gauges,
            "core_counts_before": core_before,
            "core_counts_after": core_after,
            "optional_counts_before": optional_before,
            "optional_counts_after": optional_after,
            "skipped_samples": skipped_samples,
            "skipped_series": series_rows,
            "intervals": intervals,
            "submissions": submissions,
            "submission_latency_ms": {
                "p50_ms": round(percentile([item["elapsed_ms"] for s in submissions for item in s["outcomes"]], 0.5), 2),
                "p95_ms": round(percentile([item["elapsed_ms"] for s in submissions for item in s["outcomes"]], 0.95), 2),
            },
        }

    def recovery_phase(self) -> dict:
        self.stop()
        released_sample = filesystem_sample(self.state_dir)
        release_floor = max(1, released_sample["available_bytes"] // 2)
        self.write_policy(enabled=True, pause=release_floor, resume=release_floor)
        optional_before = optional_counts(self.db_path)
        core_before = core_counts(self.db_path)
        self.start()
        observed = capacity_state(self.client, self.cookie)
        if observed["protected"]:
            raise BaselineError("protection stayed open after the pause floor moved below the free space")
        rounds = self.args.recovery_rounds
        submissions = []
        for index in range(1, rounds + 1):
            submissions.append(self.submit_round(slow_scan=False, label="recovery round " + str(index)))
            if index < rounds:
                time.sleep(1.0)
        capacity_after = capacity_state(self.client, self.cookie)
        gauges = capacity_gauges(self.metrics_client)
        self.stop()
        optional_after = optional_counts(self.db_path)
        core_after = core_counts(self.db_path)
        intervals = interval_rows(self.db_path)
        expected_samples = rounds * AGENT_COUNT * (len(HOST_METRICS) + NODES_PER_AGENT * len(STEADY_NODE_METRICS))
        observed_samples = (optional_after["host_samples"] - optional_before["host_samples"]) + (
            optional_after["node_samples"] - optional_before["node_samples"]
        )
        self.checks.append(Check("recovery optional samples resumed", expected_samples, observed_samples))
        closed = [row for row in intervals if row["ended_at"] is not None]
        self.checks.append(Check("protection interval closed once", 1, len(closed)))
        if closed:
            self.checks.append(Check("closure reason", "resumed", closed[-1]["ended_reason"]))
        return {
            "rounds": rounds,
            "release_floor_bytes": release_floor,
            "mount_available_bytes": released_sample["available_bytes"],
            "capacity_after": capacity_after,
            "capacity_gauges": gauges,
            "core_counts_before": core_before,
            "core_counts_after": core_after,
            "optional_counts_before": optional_before,
            "optional_counts_after": optional_after,
            "intervals": intervals,
            "skipped_series": skipped_series_rows(self.db_path),
            "submissions": submissions,
        }

    def run(self) -> dict:
        started_wall = time.monotonic()
        self.run_root.mkdir(parents=True, exist_ok=True)
        self.state_dir.mkdir(parents=True, exist_ok=True)
        if not self.binary.is_file():
            raise BaselineError("Server binary not found at " + str(self.binary))

        if not self.args.skip_build:
            command(["cargo", "build", "-p", "platpulse-server"], cwd=ROOT, timeout=1800)
        if not (self.web_root / "index.html").is_file():
            raise BaselineError(
                "the WebUI build is missing at "
                + str(self.web_root)
                + "; run npm run build in platpulse-web, because /health/ready waits for web assets"
            )

        self.template = json.loads((FIXTURE_DIR / "report_v1_canonical.json").read_text(encoding="utf-8"))
        self.minimal = json.loads((FIXTURE_DIR / "report_v1_minimal.json").read_text(encoding="utf-8"))

        steady_sample = filesystem_sample(self.state_dir)
        if steady_sample["available_bytes"] <= STEADY_RESUME_BYTES * 2:
            raise BaselineError("the temporary state directory has too little free space to measure a baseline")
        self.write_policy(enabled=True, pause=STEADY_PAUSE_BYTES, resume=STEADY_RESUME_BYTES)

        command([self.binary, "init", "--config", self.config_path], cwd=ROOT)
        command(
            [self.binary, "owner", "create", "--config", self.config_path, "--username", OWNER_USERNAME],
            input_text=OWNER_PASSWORD + "\n",
            cwd=ROOT,
        )
        # Enrollment Tokens are minted while the Server is stopped. A CLI write
        # racing the running Server corrupts the shared WAL index in
        # development mode, which is the deployment this baseline measures.
        tokens = [create_enrollment_token(self.binary, self.config_path) for _ in range(AGENT_COUNT)]
        self.start()
        self.cookie, self.csrf = login(self.client, OWNER_USERNAME, OWNER_PASSWORD)

        status, _, payload, _ = admin_post(
            self.client, self.cookie, self.csrf, "/api/admin/v1/networks", NETWORK
        )
        if status != 200:
            raise BaselineError(
                "Network registration failed with status " + str(status) + ": " + payload.decode("utf-8")[:400]
            )

        for agent_index, token in enumerate(tokens):
            self.agents.append(enroll_agent(token, self.client, agent_index))
        visible = agent_diagnostics(self.client, self.cookie)
        self.checks.append(Check("enrolled agents visible to the Server", AGENT_COUNT, len(visible)))

        self.stop()
        baseline = {
            "core": core_counts(self.db_path),
            "optional": optional_counts(self.db_path),
            "storage": storage_bytes(self.db_path),
        }
        self.start()

        steady = self.steady_phase(baseline)
        reads = steady["read_path"]
        mounted = mount_conditions(self.state_dir)
        sample_after = filesystem_sample(self.state_dir)
        pressure = self.pressure_phase(sample_after["available_bytes"])
        recovery = self.recovery_phase()
        self.stop()

        storage = storage_bytes(self.db_path)
        self.runtime_seconds = time.monotonic() - started_wall
        self.report = {
            "issue": 212,
            "story": 46,
            "generated_at": utc_now(),
            "run_root": str(self.run_root),
            "duration_seconds": round(self.runtime_seconds, 2),
            "seed": self.args.seed,
            "disclaimer": [
                "This is a measured baseline on one developer machine, not a production capacity guarantee.",
                "The optional history measured here is the existing generic optional metric writer "
                "(node_metric_samples, host_metric_samples). No other history family was implemented or measured.",
                "The 30 day precision-tier retention window described by the parent specification was not exercised: "
                "the baseline covers minutes of wall clock time, not a 30 day projection.",
            ],
            "conditions": {
                "hardware": hardware_conditions(),
                "mount": mounted,
                "filesystem_sample_at_start": steady_sample,
                "filesystem_sample_at_end": sample_after,
                "build": {
                    "binary": str(self.binary),
                    "bytes": file_bytes(self.binary),
                    "built_at": datetime.fromtimestamp(self.binary.stat().st_mtime, timezone.utc).strftime(
                        "%Y-%m-%dT%H:%M:%SZ"
                    ),
                    "profile": "debug",
                    "note": "A debug-profile build understates throughput; the report does not extrapolate it.",
                },
                "web_build_served": {
                    "web_root": str(self.web_root),
                    "index_built_at": datetime.fromtimestamp(
                        (self.web_root / "index.html").stat().st_mtime, timezone.utc
                    ).strftime("%Y-%m-%dT%H:%M:%SZ"),
                    "note": "The Server refuses to become ready without web assets; the served WebUI build is not "
                    "part of the capacity measurement.",
                },
                "cadence": {
                    "fast_path_seconds": self.args.interval,
                    "fast_path_agents": AGENT_COUNT,
                    "fast_path_nodes_per_agent": NODES_PER_AGENT,
                    "slow_scan_every_rounds": SLOW_SCAN_EVERY,
                    "slow_scan_carries": ["data_directory_size_bytes", "data_directory_capacity_bytes", "chain.peers"],
                    "capacity_sampling_seconds": FAST_SAMPLE_SECONDS,
                },
                "load_generator": {
                    "kind": "deterministic Reports submitted over the real Agent ingestion HTTP surface",
                    "seed": self.args.seed,
                    "substitution": "No live platpulse-agent process ran, so Agent-side collection cost is not measured.",
                },
                "database": {
                    "path": str(self.db_path),
                    "schema_version": sqlite_scalar(self.db_path, "SELECT MAX(version) FROM _sqlx_migrations"),
                },
            },
            "topology": {
                "agents": [{"agent_id": agent["agent_id"], "agent_epoch": agent["agent_epoch"]} for agent in self.agents],
                "nodes": [{"agent_index": index, "node_ids": ids} for index, ids in enumerate(self.node_ids)],
                "network": NETWORK,
            },
            "phases": {"steady": steady, "pressure": pressure, "recovery": recovery},
            "read_path": reads,
            "storage": storage,
            "storage_per_report_bytes": {
                "measured_at": "live readings taken while the Server was still running; a reading taken after "
                "the stop cannot see the WAL, because closing the last connection checkpoints it away.",
                "database_bytes_per_report": round(
                    (steady["storage_after"]["database_bytes"] - steady["storage_before"]["database_bytes"])
                    / max(1, steady["submissions"]),
                    2
                ),
                "wal_bytes_per_report": round(
                    (steady["storage_after"]["wal_bytes"] - steady["storage_before"]["wal_bytes"])
                    / max(1, steady["submissions"]),
                    2
                ),
                "wal_peak_bytes": steady["storage_peak"]["wal_bytes"],
                "database_peak_bytes": steady["storage_peak"]["database_bytes"],
                "after_shutdown": steady["storage_after_shutdown"],
            },
            "thresholds": {
                "steady_test_pause_bytes": STEADY_PAUSE_BYTES,
                "steady_test_resume_bytes": STEADY_RESUME_BYTES,
                "max_persisted_bytes": MAX_PERSISTED_BYTES,
                "rationale": [
                    "The Server invents no threshold: [capacity] enabled = true requires pause_below_bytes and "
                    "resume_above_bytes, so an operator must measure the deployment.",
                    "The steady-phase thresholds are deliberately small test values (1 GiB pause, 2 GiB resume) placed "
                    "roughly an order of magnitude below the mount free space, which keeps protection off while the "
                    "write path is measured: " + human_bytes(steady_sample["available_bytes"]) + " was available.",
                    "The pressure phase declares pause = resume = i64::MAX, the largest value the Server can persist "
                    "(CapacityConfig::MAX_PERSISTED_BYTES), so protection opens for any real mount while the "
                    "filesystem itself is never filled.",
                    "The recovery phase declares pause = resume = half of the measured free space, which is the "
                    "release the Server then records with reason 'resumed'.",
                ],
            },
            "not_delivered": [
                "No history family beyond the generic optional metric writer was built or measured.",
                "No 30 day retention or precision-tier downsampling was exercised; the visible gap evidence covers "
                "minutes, and upscaled old buckets were never produced.",
                "Agent-side collection was not measured: Reports were generated by the loader, not by a live "
                "platpulse-agent process, and validator hosts were not contacted.",
                "Only one mount, one filesystem and one writer path were measured; no multi-disk or network "
                "filesystem deployment was exercised.",
                "The Server ran in development mode without TLS and without a reverse proxy.",
                "A release-profile build was not measured.",
                "These items must be appended to this same report by a follow-up ticket; nothing here is a production "
                "guarantee.",
            ],
            "checks": [check.as_json() for check in self.checks],
        }
        return self.report


def write_json_report(report: dict, path: Path) -> None:
    path.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")


